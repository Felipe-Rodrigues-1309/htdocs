CREATE TABLE IF NOT EXISTS training_evaluations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_empresa VARCHAR(500) NOT NULL,
  cnpj VARCHAR(14),
  treinamento_no_horario VARCHAR(20) NOT NULL
    CHECK (treinamento_no_horario IN ('Sim', 'Não')),
  uso_sistema VARCHAR(20) NOT NULL
    CHECK (uso_sistema IN ('Sim', 'Parcialmente', 'Não')),
  avaliacao_geral VARCHAR(20) NOT NULL
    CHECK (avaliacao_geral IN ('Excelente', 'Bom', 'Mediano', 'Ruim', 'Péssimo')),
  nota_indicacao SMALLINT NOT NULL
    CHECK (nota_indicacao BETWEEN 1 AND 5),
  feedback TEXT,
  data_envio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS training_evaluations_data_envio_idx
  ON training_evaluations (data_envio);

CREATE INDEX IF NOT EXISTS training_evaluations_cnpj_idx
  ON training_evaluations (cnpj);
